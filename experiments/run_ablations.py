"""
experiments/run_ablation.py

Orchestrates the ablation control experiments:
1. Direct Equation Ablation
2. No-CoT Ablation
3. CoT Ablation

Loads results from the patching phase and applies zero-ablation.
"""

import sys
import os
import pandas as pd
from tqdm import tqdm

# Add root project directory to sys.path
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from src.utils import load_model
from src.ablation import (
    run_direct_equation_ablation_using_curated_heads,
    run_nocot_ablation_using_curated_heads,
    run_cot_ablation_using_curated_heads
)

# Helper for loading JSON results
from src.ablation import load_heads_from_experiment

def main():
    # 1. Load Model
    print("Loading Model...")
    model = load_model("qwen2.5-0.5b", device="cuda")

    # 2. Load Dataset
    data_path = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'data', 'processed', 'svamp_curated_subset.json'))
    print(f"Loading Dataset from {data_path}...")
    sampled_df = pd.read_json(data_path)

    # 3. Define the experiment files (Source of 'selected_heads')
    # These are the files generated by your run_patching.py
    results_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'results'))
    
    experiment_files = [
        "multi_head_patching_with_jsd_results.json",
        "multi_head_cross_patching_with_jsd_results.json",
        "multi_head_patching_with_margin_results.json",
        "multi_head_cross_patching_with_margin_results.json",
        "random_patching_with_jsd_results.json",
        "random_patching_with_margin_results.json"
    ]

    all_results = {}

    for file_name in experiment_files:
        # Tam dosya yolunu oluştur
        file_path = os.path.join(results_dir, file_name)
        
        print(f"\n{'='*20} Processing {file_name} {'='*20}")
        
        # Load curated heads
        curated_heads = load_heads_from_experiment(file_path)
        if not curated_heads:
            print(f"No heads found for {file_path}, skipping.")
            continue

        prefix = file_path.replace(".json", "")

        # --- A. Equation Ablation ---
        print("[1/3] Running Equation Ablation...")
        df_eq = run_direct_equation_ablation_using_curated_heads(sampled_df, model, curated_heads)
        df_eq.to_csv(f"{prefix}_ablation_Equation.csv", index=False)
        print(f"Equation Accuracy: {df_eq['ablation_correct'].mean():.2%}")

        # --- B. No-CoT Ablation ---
        print("[2/3] Running No-CoT Ablation...")
        df_nocot = run_nocot_ablation_using_curated_heads(sampled_df, model, curated_heads)
        df_nocot.to_csv(f"{prefix}_ablation_NoCoT.csv", index=False)
        print(f"No-CoT Accuracy: {df_nocot['ablation_correct'].mean():.2%}")

        # --- C. CoT Ablation ---
        print("[3/3] Running CoT Ablation...")
        df_cot = run_cot_ablation_using_curated_heads(sampled_df, model, curated_heads)
        df_cot.to_csv(f"{prefix}_ablation_CoT.csv", index=False)
        print(f"CoT Accuracy: {df_cot['ablation_correct'].mean():.2%}")

    print("\nAll ablation experiments completed successfully.")

if __name__ == "__main__":
    main()